// ---------- JSON-LD builders ----------
export const faqLd = (items = FAQS) => ({
  "@context": "https://schema.org",
  "@type": "FAQPage",
  mainEntity: items.map((f) => ({
    "@type": "Question",
    name: f.q,
    acceptedAnswer: { "@type": "Answer", text: f.a },
  })),
});

export const breadcrumbLd = (crumbs) => ({
  "@context": "https://schema.org",
  "@type": "BreadcrumbList",
  itemListElement: crumbs.map((c, i) => ({
    "@type": "ListItem",
    position: i + 1,
    name: c.name,
    item: `${SITE.url}${c.path}`,
  })),
});

export const serviceLd = (s, areaName) => ({
  "@context": "https://schema.org",
  "@type": "Service",
  name: areaName ? `${s.name} in ${areaName}` : s.name,
  description: s.description,
  serviceType: s.name,
  provider: { "@type": "LocalBusiness", "@id": `${SITE.url}/#business`, name: SITE.name },
  areaServed: areaName
    ? { "@type": "AdministrativeArea", name: `${areaName}, ${SITE.district}` }
    : { "@type": "AdministrativeArea", name: SITE.district },
  url: `${SITE.url}/services/${s.slug}`,
});
